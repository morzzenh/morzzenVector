from pydantic import BaseModel, Field

# БЫЛО: from app.config import SEARCH_TOP_K
# БЫЛО: from app.config import settings
# СОКРАЩЕНО: from app import settings (витрина пакета, см. app/__init__.py)
from app import settings

# СТРУКТУРА: схемы запросов/ответов API вынесены отдельно от эндпоинтов.

# УЛУЧШЕНИЕ: параметры поиска во входной модели с валидацией. Раньше был голый `question: str`

class SearchRequest(BaseModel):
    question: str = Field()
    # top_k — сколько самых релевантных фрагментов (чанков) вернуть в ответе поиска.
    # Поиск сортирует все чанки по близости к вопросу и отдаёт первые top_k лучших.
    #   Мало (1–3): коротко и точно, но можно упустить нужный фрагмент, если он не на первом месте.
    #   Много (10–20): выше шанс захватить нужное, но больше «шума» и, если результаты потом
    #   передаются в LLM, — больше токенов и риск запутать модель. Обычно 3–10; по умолчанию 5.
    # Название из ML/поиска: «top-k results» (k лучших результатов).
    # Ограничение le=20 защищает БД от запросов «верни всё».
    top_k: int = Field(default=settings.SEARCH_TOP_K, ge=1, le=20)
