# Зачем нужен файл __init__.py?
#
# 1. Он превращает папку в ПАКЕТ — то, что можно импортировать: `app` — это папка app/,
#    `app.config` — файл app/config.py внутри неё.
#
# 2. Через него пакет показывает «витрину» — то, что удобно импортировать коротко.
#    Здесь это настройки. Благодаря строке ниже во всём проекте пишем:
#        from app import settings
#    вместо длинного:
#        from app.config import settings
#    Код из __init__.py выполняется ОДИН раз при первом импорте пакета.
#
# 3. __all__ — явный список публичных имён пакета. Его используют `from app import *`,
#    IDE (подсказки) и линтеры (ruff не ругается на «неиспользуемый» импорт в __init__.py,
#    если имя есть в __all__). Всё, чего в списке нет, считается внутренним.
#
# 4. Номер версии проекта живёт здесь же: `import app; app.__version__`.
#
# ВАЖНОЕ ПРАВИЛО, чтобы не словить циклический импорт (ImportError):
#   * ИЗ ДРУГИХ пакетов импортируем коротко:  from app.db import init_db
#   * ВНУТРИ одного пакета импортируем модуль напрямую:  from app.db.models import Base
#     (в app/db/session.py, а не `from app.db import Base`: пакет к тому моменту ещё не дозагружен).
#   * Этот файл импортирует только app.config, который сам ничего из app не импортирует.
#     Подпакеты (api, db, services) сюда НЕ подключаем — они зависят от settings.
#
# ---- Как работали бы импорты БЕЗ этого файла ----
# Проверено: если удалить все __init__.py, приложение всё равно запускается и импорты вида
#     from app.config import settings
# работают — Python (3.3+) считает папку «пакетом-пространством имён» (запуск из корня проекта).
# Но тогда ПОТЕРЯЕТСЯ:
#   * `from app import settings` и `app.__version__` — выполнять в папке нечего;
#   * `app.__file__` будет None; pytest/mypy/Poetry хуже понимают границы пакета;
#   * при двух папках `app` в sys.path Python склеит их в один пакет; обычный пакет
#     (с __init__.py) такого не допускает;
#   * на Python старше 3.3 импорт упал бы с ModuleNotFoundError.

from app.config import settings

__version__ = '0.1.0'

__all__ = ['settings', '__version__']
